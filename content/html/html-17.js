const FOCUSABLE = 'a[href], button, input, select, textarea, summary, iframe, [tabindex]';

function skipLink(c) {
  const first = c.q('body a[href]');
  const main = c.q('body > main');
  if (!first || !main) return null;
  const href = first.getAttribute('href').trim();
  return href.startsWith('#') && main.getAttribute('id') === decodeURIComponent(href.slice(1)) && first.textContent.trim().length >= 5 ? first : null;
}

const badHidden = c => c.qa('[aria-hidden="true" i]').find(el => el.matches(FOCUSABLE) || el.querySelector(FOCUSABLE));
const nameless = c => c.qa('body a[href], body button').find(el =>
  !el.textContent.trim() && !(el.getAttribute('aria-label') || '').trim() &&
  !el.querySelector('img[alt]:not([alt=""])'));

