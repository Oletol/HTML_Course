const HEADINGS = 'body h1, body h2, body h3, body h4, body h5, body h6';

function headingLevels(c) {
  return c.qa(HEADINGS).map(h => Number(h.tagName[1]));
}

function sectionsHaveParagraphs(c) {
  let current = null, has = false, ok = true;
  c.qa(`${HEADINGS}, body p`).forEach(el => {
    if (el.tagName === 'H2' || el.tagName === 'H1') {
      if (current && !has) ok = false;
      current = el.tagName === 'H2' ? el : null;
      has = false;
    } else if (el.tagName === 'P' && el.textContent.trim().length >= 20) {
      has = true;
    }
  });
  if (current && !has) ok = false;
  return ok;
}

