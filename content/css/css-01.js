/* Совпадает ли вычисленный цвет элемента с заданным значением */
function sameColor(m, el, value) {
  const probe = m.doc.createElement('span');
  probe.style.color = value;
  m.doc.body.append(probe);
  const want = m.cs(probe).color;
  probe.remove();
  return Boolean(el) && m.cs(el).color === want;
}

